#!/usr/bin/env bash
# The change adds a discount field named amt2 to the schema, so renaming it means rebuilding src/generated/order.ts.
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/../_shared/shop-lib.sh"
cat > package.json <<'X'
{ "name": "shop", "private": true, "type": "module", "scripts": { "test": "bash scripts/test.sh", "gen": "node scripts/gen.mjs" } }
X
mkdir -p schema src/generated
cat > scripts/gen.mjs <<'X'
// Writes src/generated/order.ts from schema/order.json.
import { readFileSync, writeFileSync } from "node:fs";

const { fields } = JSON.parse(readFileSync("schema/order.json", "utf8"));
const lines = Object.entries(fields).map(([name, type]) => `    /** From schema/order.json. */\n    ${name}: ${type};`);
writeFileSync("src/generated/order.ts", `// Generated by scripts/gen.mjs. Do not edit.\nexport type Order = {\n${lines.join("\n")}\n};\n`);
X
echo '{ "fields": { "id": "string", "total": "number" } }' > schema/order.json
node scripts/gen.mjs
git add -A && git commit -q -m "feat: order type from the schema" && git push -q
echo '{ "fields": { "id": "string", "total": "number", "amt2": "number" } }' > schema/order.json
node scripts/gen.mjs
cat > src/summary.ts <<'X'
import type { Order } from "./generated/order.ts";

/** The order total after its discount. */
export const amountDue = (order: Order): number => order.total - order.amt2;
X
finish_shop
